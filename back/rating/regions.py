"""Регионы Казахстана — закреплённый список ✳ (16.09.2026).

Замечания федерации (docs/refs/zamechaniya-regiony-pol-partii-2026-09-16.md):
«регионы были фиксированные 3 города и 17 областей, чтобы конкретно просто
выбрать регион». Свободная строка давала три написания одного региона
(«Павлодар», «Павлодарская обл.», «Павлодарская область»), и выборка по региону
переставала сходиться.

Список — административное деление РК после 2022 года: три города
республиканского значения и семнадцать областей. Он один и живёт здесь: экран
берёт его с сервера (`GET /api/rating/regions/`), а не повторяет у себя.

Уже загруженные карточки написаны иначе («БҚО», «Қарағанды обл.») — их проверка
не трогает, приведение старых значений решается с федерацией (QUESTIONS).
"""
from typing import List, Optional

#: Города республиканского значения.
CITIES: List[str] = ["Астана", "Алматы", "Шымкент"]

#: Области.
OBLASTS: List[str] = [
    "Абайская область",
    "Акмолинская область",
    "Актюбинская область",
    "Алматинская область",
    "Атырауская область",
    "Восточно-Казахстанская область",
    "Жамбылская область",
    "Жетысуская область",
    "Западно-Казахстанская область",
    "Карагандинская область",
    "Костанайская область",
    "Кызылординская область",
    "Мангистауская область",
    "Павлодарская область",
    "Северо-Казахстанская область",
    "Туркестанская область",
    "Улытауская область",
]

#: Города идут первыми: в них живёт большинство спортсменов.
REGIONS: List[str] = CITIES + OBLASTS


def clean(region) -> Optional[str]:
    """Регион из списка, пустая строка — «не указан», иначе None (не наш)."""
    value = str(region or "").strip()
    if not value:
        return ""
    return value if value in REGIONS else None
