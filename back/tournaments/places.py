_REGION_OF = {city: region for region, cities in OBLAST_CITIES.items() for city in cities}
_REGION_OF.update({city: city for city in CITIES})


def directory() -> List[dict]:
    """Справочник для экрана в порядке `REGIONS`. У города республиканского
    значения своих городов нет: регион и есть город."""
    return [{"region": region, "cities": OBLAST_CITIES.get(region, [])} for region in REGIONS]


def clean(region, city) -> Optional[Tuple[str, str]]:
    """Пара (регион, город) по справочнику; None — такой пары нет.

    Город без региона получает свой регион; город республиканского значения
    всегда сам себе и регион, и город; пустая пара — «не указано»."""
    region, city = str(region or "").strip(), str(city or "").strip()
    if not region and not city:
        return "", ""
    if city:
        owner = _REGION_OF.get(city)
        if owner is None or (region and region != owner):
            return None
        return owner, city
    if region not in REGIONS:
        return None
    return region, region if region in CITIES else ""
