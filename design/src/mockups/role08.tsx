export function Live8_2() {
  /* Доступ у заместителя или уже возвращён главному. Вернуть можно всегда —
     взять самому нельзя: доступ выдаёт главный судья. */
  const [on, setOn] = useState(true);
  /* Что заместитель успел сделать. Журнал растёт по ходу и подписан его
     именем — это и есть «пометка, что заполнял он». */
  const [log, setLog] = useState<{ t: string; at: string }[]>([]);
  const at = (i: number) => `14:${String(22 + i * 3).padStart(2, '0')}`;

  return (
    <RoleScreen
      role={R08}
      nav="Ход турнира"
      title={on ? 'Ход турнира — замещаю' : 'Ход турнира — только просмотр'}
      sub="12 столов в игре · 8 пар ждут стола · сыграно 60 из 127 матчей"
    >
      <div className="dactionbar">
        <div className="dcount">
          <ArrowRightLeft size={13} style={{ display: 'inline-block', verticalAlign: '-2px', marginRight: 6 }} />
          {on
            ? 'Доступ выдан в 14:20 · выдал Оспанов Т., главный судья'
            : 'Доступ возвращён главному судье · действия закрыты'}
        </div>
        <div style={{ display: 'flex', alignItems: 'center', gap: 10 }}>
          <span className={'pill ' + (on ? 'live' : 'done')} style={{ margin: 0 }}>
            {on ? 'ЗАМЕЩАЮ' : 'ДОСТУПА НЕТ'}
          </span>
          <button type="button" className="dpickbtn" onClick={() => setOn(!on)}>
            {on ? 'Вернуть доступ главному' : 'Запросить доступ'}
          </button>
        </div>
      </div>

      {/* Действия — своей полосой во всю ширину ✳, а не внутри панели «Идут
          сейчас». Пять кнопок, зажатые в колонку рядом с карточками матчей,
          наезжали друг на друга и отнимали место у самого главного — у того,
          что на столах происходит. Здесь их видно целиком и они не мешают
          контенту. */}
      {on ? (
        <Panel
          title="Что можно сделать с доступом"
          extra={<span className="dcount">каждое действие — в журнал с именем заместителя</span>}
        >
          <div style={{ display: 'flex', flexWrap: 'wrap', gap: 8 }}>
            {DEP_ACTS.map((a) => (
              <button
                type="button"
                className="dpickbtn"
                key={a.t}
                onClick={() => setLog([{ t: a.log, at: at(log.length) }, ...log].slice(0, 6))}
              >
                <span style={{ display: 'inline-flex', alignItems: 'center', gap: 6 }}>
                  {a.ic}{a.t}
                </span>
              </button>
            ))}
          </div>
        </Panel>
      ) : (
        <Alert>
          Доступа нет — экран на просмотр. Выдать его может только главный судья: взять самому
          нельзя, иначе за пультом окажутся двое ✳.
        </Alert>
      )}

      <TableMap />

      <div className="dcols">
        <Panel title="Идут сейчас" extra={<span className="pill live" style={{ margin: 0 }}>12 СТОЛОВ В ИГРЕ</span>}>
          <LiveCards />
        </Panel>

        <QueuePanel />
      </div>

      {/* Журнал — своей панелью под колонками: он растёт по ходу смены, и в
          узкой колонке строки ломались бы на два ряда. */}
      {log.length > 0 && (
        <Panel
          title="Что сделал заместитель"
          extra={<span className="pill reg" style={{ margin: 0 }}>{log.length} В ЖУРНАЛЕ</span>}
        >
          <Rows>
            {log.map((l) => (
              <Row
                key={l.at + l.t}
                nm={l.t}
                sub={`${l.at} · Сагинтаев Д., заместитель главного судьи`}
                pill={{ t: 'В ЖУРНАЛЕ', cls: 'reg' }}
              />
            ))}
          </Rows>
          <div style={{ marginTop: 10 }}>
            <Hint>
              Пометка об авторе — не украшение ✳: результат, внесённый заместителем за секретаря,
              на разборе отличается от внесённого секретарём, и спор о счёте начинается именно с
              вопроса «кто вносил».
            </Hint>
          </div>
        </Panel>
      )}
    </RoleScreen>
  );
}

