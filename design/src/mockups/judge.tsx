/** История судейства: пять однородных колонок, коэффициент читается колонкой
    сверху вниз — видно, за что дали полтора. Шапка у «моего рейтинга» и у
    карточки своя (слова разные), таблица одна. */
function TourTable({
  tours,
  cols,
  /** В карточке строки «Член ГСК» помечены: заседание — это S4, а не S1. */
  committee,
}: {
  tours: JudgeTour[];
  cols: [what: string, role: string, points: string];
  committee?: boolean;
}) {
  const grid = 'minmax(0,1.9fr) minmax(0,1.1fr) minmax(0,1.4fr) minmax(0,1fr) 72px';
  return (
    <Sheet flush cols={[cols[0], 'Когда и где', cols[1], 'Коэффициент', <Th key="p">{cols[2]}</Th>]} grid={grid}>
      {tours.map((t) => {
        const pts = tourPoints(t);
        return (
          <div key={t.nm + t.when} className="grid items-center gap-3 px-4 py-2.5 text-[13px]" style={{ gridTemplateColumns: grid }}>
            <span className="min-w-0 leading-tight">
              <span className="block truncate font-medium">{t.nm}</span>
              <span className="block truncate text-xs text-neutral-500">{t.kind} · базовый балл {num(t.base)}</span>
            </span>
            <span className="text-neutral-600">{t.when} · {t.city}</span>
            <span className="min-w-0 leading-tight text-neutral-700">
              {t.post}
              {/* Работа в коллегии — не S1 ✳: членство в ГСК идёт в S4, и такие
                  строки помечены отдельно. Иначе таблица показывала бы «отсудил
                  14 соревнований» там, где человек не судил, а заседал. */}
              {committee && t.post === 'Член ГСК' && (
                <span className="block text-[11px] text-neutral-400">идёт в S4, а не в S1</span>
              )}
            </span>
            <span className={t.miss || t.k === 1 ? 'text-neutral-500' : 'font-medium text-neutral-800'}>
              {t.miss ? '—' : t.k === 1 ? 'без коэффициента' : '× ' + num(t.k)}
            </span>
            {/* Неявка — единственное красное число таблицы: минус балл (§7.2). */}
            <span className={'text-right font-semibold tabular-nums ' + (pts < 0 ? 'text-red-600' : 'text-neutral-800')}>
              {sign(pts)}
            </span>
          </div>
        );
      })}
    </Sheet>
  );
}

/* ── Экран «Мой рейтинг судьи» ──────────────────────────────────── */

/** Что видит про себя любой судья: из чего сложился рейтинг и что с ним делать.

    Два блока и счётчики над ними — больше на экране ничего нет. Первый блок
    система посчитала сама (судейство по явке — S1), второй судья принёс сам
    (награды, семинары, работа в коллегии — S3 и S4). Апелляция с экрана убрана
    (18.08.2026): она бывает раз в период и только после публикации рейтинга —
    держать ради неё третий блок на каждый день незачем, она живёт в состояниях
    экрана и приходит уведомлением.

    История судейства — таблица, а не строки списка: у неё пять однородных
    колонок, и коэффициент читается колонкой сверху вниз — видно, за что дали
    полтора. */
export function JudgeRating({ me, tours }: { me: JudgeMe; tours: JudgeTour[] }) {
  const r = me.s1 + me.s2 + me.s3 + me.s4;
  /* Зачёт — не украшение: баллы не меньше чем в трёх категориях из четырёх, и
     S1 с S2 обязательны (§6.3.1 Положения). Без зачёта места в рейтинге нет, и
     судья должен видеть это раньше председателя. */
  const parts = [me.s1, me.s2, me.s3, me.s4].filter((x) => x > 0).length;
  const ok = parts >= 3 && me.s1 > 0 && me.s2 > 0;

  return (
    <>
      {/* Одна полоса, а не две: слагаемые стоят формулой в подписи под R —
          так видно и итог, и из чего он сложился, а экран не съедается
          восемью плитками. Судья приходит сюда именно за «чего не хватает». */}
      {/* Балла R в плитках нет ✳ (04.09.2026): он же стоит в центре кольца
          ниже, вместе с разбивкой S1–S4 — то есть число и его формула
          показывались дважды, в сантиметре друг от друга. В плитках остаётся
          то, чего в кольце нет: место, категория и зачёт. Правило зачёта из
          подписи убрано — оно живёт подписью панели рядом. */}
      <StatTiles
        items={[
          { v: '№' + me.pl, k: 'Место в рейтинге сезона' },
          { v: me.cat, k: 'Регион учёта ' + me.region },
          { v: ok ? 'ЕСТЬ' : 'НЕТ', k: 'Зачёт', tone: ok ? 'g' : 'a' },
        ]}
      />

      {/* Из чего сложился балл и как он набирался ✳ (31.08.2026). Формула под
          числом отвечает «сколько», но не отвечает «чего не хватает»: у судьи
          с R = 9 весь балл может быть из одной категории, а зачёт требует трёх
          из четырёх. Кольцо показывает это одним взглядом, столбики — из каких
          турниров пришёл S1. */}
      <Panel title="Слагаемые" extra={<Cap>Зачёт — баллы не меньше чем в трёх категориях из четырёх</Cap>}>
        <ChartRow>
          <Donut
            label={'Слагаемые рейтинга: S1 ' + num(me.s1) + ', S2 ' + num(me.s2) + ', S3 ' + num(me.s3) + ', S4 ' + num(me.s4)}
            total={num(r)}
            totalNote="балл R"
            parts={[
              { t: 'S1 · работа на турнирах', v: me.s1, note: 'по явке' },
              { t: 'S2 · категория', v: me.s2 },
              { t: 'S3 · награды и звания', v: me.s3 },
              { t: 'S4 · семинары и коллегия', v: me.s4 },
            ]}
          />
          <Bars
            label="Баллы S1 по турнирам сезона"
            suffix="баллов S1 за турнир"
            items={tours.map((t) => ({ t: t.nm.split(' ')[0], v: tourPoints(t) }))}
          />
        </ChartRow>
      </Panel>

      <Panel
        title={'История судейства в турнирах · ' + tours.length + ' за сезон'}
        extra={<Cap>S1 система начисляет сама, по явке</Cap>}
        flush
      >
        <TourTable tours={tours} cols={['Турнир', 'Моя роль в наряде', 'Балл S1']} />
        <Foot>
          Коэффициент 1,5 — за роль в бригаде (главный судья, заместитель, секретарь) и за выезд на
          республиканские из другого региона; неявка по заявке — минус балл без коэффициента (TZ §7.2)
        </Foot>
      </Panel>

      {/* Второй блок — то, что судья приносит сам: награды, семинары, работа в
          коллегии (S3 и S4). Система о них не знает, пока не увидит документ
          (TZ §7.2). Добавить можно в любой момент, подать — когда готов: у
          черновика своя кнопка в строке. */}
      <Panel
        title="Награды и документы · S3 и S4"
        extra={
          <Button size="sm" variant="outline">
            <FileUp size={14} /> Добавить
          </Button>
        }
        flush
      >
        <div className="divide-y divide-neutral-100">
          {JUDGE_DOCS.map((d) => (
            <Row
              key={d.t}
              nm={d.t}
              sub={d.sub}
              pill={{ t: d.st, cls: d.cls }}
              action={d.send ? 'Подать' : undefined}
            />
          ))}
        </div>
        <Foot>
          Баллы по документам подсказывает Положение, подтверждает председатель ГСК (Э5.6). Смена
          категории — тоже документ: он обновляет её в профиле, и дальше S2 идёт автоматически
        </Foot>
      </Panel>
    </>
  );
}

