/* Судейская часть, общая для ролей 6, 7, 8 и 9.

   Рейтинг судьи один на всех, кто судит: председатель ГСК ведёт его по
   Положению (TZ §7.2), а видит его про себя каждый судья — и главный судья, и
   секретарь, и заместитель, и судья стола. Баллы им начисляются по одной
   таблице и за одно и то же, поэтому и экран у них один: четыре копии «моего
   рейтинга» разъехались бы на первой же правке Положения.

   Разный только человек: имя, категория, место в рейтинге и то, в какой роли
   он стоял в наряде — от роли зависит коэффициент 1,5 (§7.2). */

import { FileUp } from 'lucide-react';
import { Chips, Panel, Row, Rows } from './shell';

/* ── Кто перед нами ─────────────────────────────────────────────── */

/** Судья глазами рейтинга: категория, регион учёта и слагаемые R.

    Регион здесь не справка: за судейство республиканских соревнований в
    командировке из другого региона идёт коэффициент 1,5 (§7.2), поэтому он
    указывается ещё при регистрации (Э0.7). */
export type JudgeMe = {
  nm: string;
  cat: string;
  region: string;
  /** Место в рейтинге сезона. */
  pl: number;
  s1: number; s2: number; s3: number; s4: number;
};

/** Один турнир в истории судейства: где стоял, в какой роли и что начислили.

    Роль в наряде и выезд — не украшение строки, а то, из чего сложился балл:
    главный судья, заместитель и секретарь получают коэффициент 1,5, и он же
    даётся за республиканские соревнования в командировке (§7.2). */
export type JudgeTour = {
  nm: string;
  when: string;
  city: string;
  /** Статус соревнования по Таблице 1 Положения — им задаётся базовый балл. */
  kind: 'Региональные' | 'Республиканские' | 'Международные в РК';
  /** Роль в наряде: от неё коэффициент. */
  post: string;
  /** Базовый балл и коэффициент — как в журнале у председателя (Э5.5). */
  base: number;
  k: number;
  /** Судья заявился и не вышел: минус балл (Таблица 1). */
  miss?: boolean;
};

/** Базовый балл по статусу соревнования — Таблица 1 Положения (§7.2). */
export const S1_BASE: Record<JudgeTour['kind'], number> = {
  Региональные: 1,
  Республиканские: 3,
  'Международные в РК': 5,
};

const num = (n: number) => String(Math.round(n * 10) / 10).replace('.', ',');
const sign = (n: number) => (n < 0 ? num(n) : '+' + num(n));

/** Сколько начислено за турнир: базовый балл на коэффициент, а за неявку по
    заявке — минус балл, и коэффициент к нему не применяется. */
export const tourPoints = (t: JudgeTour) => (t.miss ? -1 : t.base * t.k);

/* ── Награды и документы: то, что судья приносит сам ─────────────── */

/** S3 и S4 судья приносит сам: система их не знает, пока не увидит документ
    (§7.2). Категория — тоже документ: он обновляет её в профиле, и дальше S2
    начисляется автоматически. */
export const JUDGE_DOCS = [
  { t: 'Офлайн-семинар Федерации · Алматы', sub: 'S3 · подан 22.03.2026 · Положение: 3 балла', st: 'ПРИНЯТ +3', cls: 'live' as const },
  { t: 'Работа в составе ГСК РК, 6 месяцев', sub: 'S4 · подан 01.07.2026 · Положение: 2 балла', st: 'ПРИНЯТ +2', cls: 'live' as const },
  { t: 'Онлайн-семинар ITTF', sub: 'S3 · подан 14.08.2026 · у рейтинговой комиссии', st: 'НА ПРОВЕРКЕ', cls: 'wait' as const },
  /* Добавленное, но не отправленное: судья складывает документы по мере того,
     как они появляются, а подаёт когда собрал. Поэтому у черновика своя
     кнопка — «Подать», а не общая внизу экрана. */
  { t: 'Благодарственное письмо акимата', sub: 'S4 · добавлено 18.08.2026 · ещё не подано', st: 'ЧЕРНОВИК', cls: 'reg' as const, send: true },
  { t: 'Протокол теста аттестации', sub: 'S3 · отклонён 27.02.2026 — «скан не читается»', st: 'ОТКЛОНЁН', cls: 'bad' as const },
];

/* ── Экран «Мой рейтинг судьи» ──────────────────────────────────── */

/** Что видит про себя любой судья: из чего сложился рейтинг и что с ним делать.

    Два блока и счётчики над ними — больше на экране ничего нет. Первый блок
    система посчитала сама (судейство по явке — S1), второй судья принёс сам
    (награды, семинары, работа в коллегии — S3 и S4). Апелляция с экрана убрана
    (18.08.2026): она бывает раз в период и только после публикации рейтинга —
    держать ради неё третий блок на каждый день незачем, она живёт в состояниях
    экрана и приходит уведомлением.

    История судейства — таблица, а не строки списка: у неё пять однородных
    колонок, и коэффициент читается колонкой сверху вниз — видно, за что дали
    полтора. */
export function JudgeRating({ me, tours }: { me: JudgeMe; tours: JudgeTour[] }) {
  const r = me.s1 + me.s2 + me.s3 + me.s4;
  /* Зачёт — не украшение: баллы не меньше чем в трёх категориях из четырёх, и
     S1 с S2 обязательны (§6.3.1 Положения). Без зачёта места в рейтинге нет, и
     судья должен видеть это раньше председателя. */
  const parts = [me.s1, me.s2, me.s3, me.s4].filter((x) => x > 0).length;
  const ok = parts >= 3 && me.s1 > 0 && me.s2 > 0;

  return (
    <>
      {/* Одна полоса, а не две: слагаемые стоят формулой в подписи под R —
          так видно и итог, и из чего он сложился, а экран не съедается
          восемью плитками. Судья приходит сюда именно за «чего не хватает». */}
      <Chips
        items={[
          {
            v: num(r),
            k: `R = S1 ${num(me.s1)} + S2 ${num(me.s2)} + S3 ${num(me.s3)} + S4 ${num(me.s4)}`,
            tone: 'b',
          },
          { v: '№' + me.pl, k: 'Место в рейтинге сезона' },
          { v: me.cat, k: 'Категория · регион учёта ' + me.region },
          {
            v: ok ? 'ЕСТЬ' : 'НЕТ',
            k: 'Зачёт: баллы в трёх категориях из четырёх, S1 и S2 обязательны',
            tone: ok ? 'g' : 'a',
          },
        ]}
      />

      <Panel
        title={'История судейства в турнирах · ' + tours.length + ' за сезон'}
        extra={<span className="dcount">S1 система начисляет сама, по явке</span>}
      >
        <div className="mktable mkjudge">
          <div className="mktable-h">
            <span>Турнир</span>
            <span>Когда и где</span>
            <span>Моя роль в наряде</span>
            <span>Коэффициент</span>
            <span>Балл S1</span>
          </div>
          <div className="mktable-b">
            {tours.map((t) => (
              <div className="mktable-r" key={t.nm + t.when}>
                <span className="nm">
                  {t.nm}
                  <em>{t.kind} · базовый балл {num(t.base)}</em>
                </span>
                <span>{t.when} · {t.city}</span>
                <span>{t.post}</span>
                <span>{t.miss ? '—' : t.k === 1 ? 'без коэффициента' : '× ' + num(t.k)}</span>
                <span className="num">{sign(tourPoints(t))}</span>
              </div>
            ))}
          </div>
        </div>
        <div className="dcount" style={{ marginTop: 10 }}>
          Коэффициент 1,5 — за роль в бригаде (главный судья, заместитель, секретарь) и за выезд на
          республиканские из другого региона; неявка по заявке — минус балл без коэффициента (TZ §7.2)
        </div>
      </Panel>

      {/* Второй блок — то, что судья приносит сам: награды, семинары, работа в
          коллегии (S3 и S4). Система о них не знает, пока не увидит документ
          (TZ §7.2). Добавить можно в любой момент, подать — когда готов: у
          черновика своя кнопка в строке. */}
      <Panel
        title="Награды и документы · S3 и S4"
        extra={
          <button className="dpickbtn">
            <FileUp size={14} /> Добавить
          </button>
        }
      >
        <Rows>
          {JUDGE_DOCS.map((d) => (
            <Row
              key={d.t}
              nm={d.t}
              sub={d.sub}
              pill={{ t: d.st, cls: d.cls }}
              action={d.send ? 'Подать' : undefined}
            />
          ))}
        </Rows>
        <div className="dcount" style={{ marginTop: 10 }}>
          Баллы по документам подсказывает Положение, подтверждает председатель ГСК (Э5.6). Смена
          категории — тоже документ: он обновляет её в профиле, и дальше S2 идёт автоматически
        </div>
      </Panel>

    </>
  );
}
