/** Строка рейтинг-листа: тот же человек, что в карточке, только сжатый до
    слагаемых. Слагаемые стоят в самом списке ✳ (комментарий федерации,
    09.2026): вопрос «почему он выше меня» решается именно ими — у одного
    добрана S3, у другого выезды с коэффициентом. */
export type JudgeRank = {
  pl: number;
  nm: string;
  av: string;
  cat: string;
  region: string;
  s1: number; s2: number; s3: number; s4: number;
  /** Сколько соревнований отсудил за период — наряд, а не всякое участие. */
  tours: number;
  /** Это я: своя строка помечена при любой сортировке. */
  me?: boolean;
  /** Категория ещё не подтверждена — S2 не начисляется, в наряд не назначают. */
  wait?: boolean;
};

const rsum = (j: { s1: number; s2: number; s3: number; s4: number }) => j.s1 + j.s2 + j.s3 + j.s4;
/** Зачёт по Положению: баллы не меньше чем в трёх категориях из четырёх,
    S1 и S2 обязательны (§6.3.1). */
const scored = (j: { s1: number; s2: number; s3: number; s4: number }) =>
  [j.s1, j.s2, j.s3, j.s4].filter((x) => x > 0).length >= 3 && j.s1 > 0 && j.s2 > 0;

/** Рейтинг судей — лист, открытый всем судьям (TZ §7.2).

    Раньше свой балл судья видел, а чужие нет: рейтинг-лист существовал только
    у председателя ГСК в реестре. Федерация потребовала прозрачности — судья
    должен видеть, откуда у него баллы, и сверять себя с другими. */
export function JudgeRankList({ rows, period }: { rows: JudgeRank[]; period: string }) {
  const mine = rows.find((r) => r.me);
  const grid = '44px minmax(0,1.9fr) minmax(0,1fr) 44px 44px 44px 44px 52px 72px 80px';
  return (
    <>
      {/* Строки фактов над листом нет ✳ (03.09.2026): все три величины уже в
          самом списке — судей столько, сколько строк, а своя строка подсвечена
          и несёт и место, и балл. Читать их дважды человек не станет, а сверять
          два источника одного числа — станет. */}

      <Panel
        /* В заголовке панели только период ✳ (04.09.2026): «Рейтинг судей»
           уже стоит заголовком экрана в сантиметре выше. */
        title={period[0].toUpperCase() + period.slice(1)}
        extra={<Cap>Слагаемые в самом списке: видно, чем один судья выше другого</Cap>}
        flush
      >
        <Sheet
          flush
          grid={grid}
          cols={[
            'Место',
            'Судья',
            'Регион',
            <Th key="s1">S1</Th>,
            <Th key="s2">S2</Th>,
            <Th key="s3">S3</Th>,
            <Th key="s4">S4</Th>,
            <Th key="r">R</Th>,
            <Th key="t">Отсужено</Th>,
            'Зачёт',
          ]}
        >
          {rows.map((j) => (
            /* Строка ведёт в карточку судьи: «посмотреть другого» — это не
               всплывающая подсказка, а тот же экран, что своя карточка. */
            <button
              key={j.nm}
              type="button"
              data-to="Э0.13"
              data-row
              /* Своя строка выделена атрибутом, а не классом: полосы реестра
                 (`ROWS`) и подсветка — селекторы одного веса, и правило с
                 `data-on` намеренно тяжелее полосы. */
              data-on={j.me ? '' : undefined}
              className="grid w-full items-center gap-3 px-4 py-2.5 text-left text-[13px] tabular-nums"
              style={{ gridTemplateColumns: grid }}
            >
              <span className="text-neutral-600">{j.pl}</span>
              <span className="flex min-w-0 items-center gap-2.5">
                <Avatar size="sm">
                  <Avatar.Image alt={j.nm} src={j.av} />
                  <Avatar.Fallback>{j.nm.slice(0, 1)}</Avatar.Fallback>
                </Avatar>
                <span className="min-w-0 leading-tight">
                  <span className="block truncate font-medium">{j.nm}</span>
                  <span className={'block truncate text-xs ' + (j.wait ? 'text-amber-700' : 'text-neutral-500')}>
                    {j.wait ? 'категория ждёт подтверждения' : j.cat}
                  </span>
                </span>
              </span>
              <span className="truncate text-neutral-600">{j.region}</span>
              <span className="text-right">{num(j.s1)}</span>
              {/* Судья без подтверждённой категории стоит в листе без S2 ✳:
                  видно, что балла нет не потому, что не работал. */}
              <span className={'text-right ' + (j.s2 === 0 ? 'text-neutral-400' : '')}>
                {j.s2 === 0 ? '—' : num(j.s2)}
              </span>
              <span className="text-right">{num(j.s3)}</span>
              <span className="text-right">{num(j.s4)}</span>
              <span className="text-right font-semibold">{num(rsum(j))}</span>
              <span className="text-right text-neutral-600">{j.tours}</span>
              <span>
                <Pill t={scored(j) ? 'ЕСТЬ' : 'НЕТ'} color={scored(j) ? 'success' : 'danger'} />
              </span>
            </button>
          ))}
        </Sheet>
        <Foot>
          Своя строка помечена при любой сортировке: судья приходит сюда сравнить себя, а не читать
          список. Период указан в шапке — рейтинг судьи считается за год (TZ §7.2)
        </Foot>
      </Panel>
    </>
  );
}

/** Карточка судьи — одна на человека ✳.

    Свою судья открывает из рейтинга, чужую — из листа или из наряда турнира.
    Разница только в том, что скрыто (контакты, файлы документов), а не в
    раскладке: иначе «посмотреть другого» превратилось бы во второй экран,
    который живёт своей жизнью и расходится с первым.

    Карточку никто не заполняет руками — она собирается из турниров, нарядов и
    подтверждённых документов и обновляется сама после каждого закрытого
    протокола. На экране это сказано строкой: иначе первый же вопрос — «а кто
    это вносил и когда обновлялось». */
export function JudgeCard({ me, tours, own, player }: {
  me: JudgeMe;
  tours: JudgeTour[];
  /** Своя карточка: видны документы и вход в апелляцию. */
  own?: boolean;
  /** Тот же человек играет ✳: судья бывает игроком и наоборот. */
  player?: { rating: number; club: string };
}) {
  const r = rsum(me);
  const ok = scored(me);
  /* «Отсужено» считает наряд, а не всякое участие: работа в коллегии идёт в S4
     (§7.2) и в счётчик соревнований не попадает. ⚠ Вопрос 17.4. */
  const duty = tours.filter((t) => t.post !== 'Член ГСК');
  return (
    <>
      <StatTiles
        items={[
          { v: num(r), k: `R = S1 ${num(me.s1)} + S2 ${num(me.s2)} + S3 ${num(me.s3)} + S4 ${num(me.s4)}` },
          { v: '№' + me.pl, k: 'Место в рейтинге сезона' },
          { v: String(duty.length), k: 'Соревнований отсужено за сезон' },
          {
            v: ok ? 'ЕСТЬ' : 'НЕТ',
            k: 'Зачёт по Положению',
            tone: ok ? 'g' : 'a',
          },
        ]}
      />

      {/* Паспортная часть и разбор балла — блок под блоком ✳ (30.08.2026):
          в две колонки «Из чего собрался балл» жался рядом с карточкой, а
          строки слагаемых просят ширины. Панель сама держит отступ снизу. */}
      <>
        <Panel>
          {/* Шапка начинается с фото — как строка листа (Э0.12): зона «Шапка
              карточки» в данных роли открывается словами «Фото, фамилия…».
              Заголовок панели не умеет аватар, поэтому шапка собрана в теле. */}
          <div className="mb-3 flex items-center gap-3 border-b border-neutral-100 pb-3">
            <Avatar size="lg">
              {me.av && <Avatar.Image alt={me.nm} src={me.av} />}
              <Avatar.Fallback>{me.nm.slice(0, 1)}</Avatar.Fallback>
            </Avatar>
            <div className="min-w-0 flex-1 leading-tight">
              <h3 className="text-[13.5px] font-semibold">{me.nm}</h3>
              <p className="mt-0.5 text-xs text-neutral-500">{me.cat} · регион учёта {me.region}</p>
            </div>
            <Pill t={own ? 'МОЯ КАРТОЧКА' : 'ТОЛЬКО ПРОСМОТР'} color={own ? 'accent' : 'warning'} />
          </div>
          {/* Паспортная часть — строками «подпись — значение»: карточка
              читается сверху вниз, а не сеткой полей формы — заполнять тут
              нечего. */}
          {/* Категории и региона учёта здесь нет ✳ (04.09.2026): оба стоят
              строкой под именем, прямо над этим списком. */}
          <KV
            items={[
              ['Категорию подтвердил', 'Судейская коллегия ФНТ РК · 05.01.2026'],
              ['В реестре с', '14.09.2021'],
            ]}
          />

          {/* Судья бывает игроком и наоборот ✳ (комментарий федерации,
              09.2026): это один человек с двумя ролями, а не два аккаунта.
              Рейтинги считаются раздельно и друг на друга не влияют. */}
          {player && (
            <div className="mt-3">
              <Rows>
                <Row
                  to="Э14.7"
                  nm="Ещё и спортсмен"
                  sub={`${player.club} · рейтинг игрока ${player.rating} — считается отдельно от судейского`}
                  pill={{ t: 'ОДИН ЧЕЛОВЕК', cls: 'reg' }}
                  action="Профиль"
                />
              </Rows>
            </div>
          )}

          <div className="mt-4">
            <Bar>
              Карточку никто не заполняет руками: она собирается из турниров, нарядов и
              подтверждённых документов и обновляется сама после каждого закрытого протокола.
              {own
                ? ' Документы на S3 и S4 и апелляция — в «Моём рейтинге».'
                : ' В чужой карточке видно только рейтинговое: контакты, файлы документов и взносы закрыты.'}
            </Bar>
          </div>
        </Panel>

        <Panel title="Слагаемые" extra={<Cap>TZ §7.2</Cap>}>
          <Rows>
            <Row nm="S1 · судейство соревнований" val={num(me.s1)} pill={{ t: 'АВТО', cls: 'live' }} />
            <Row nm="S2 · квалификационная категория" val={num(me.s2)} pill={{ t: 'АВТО', cls: 'live' }} />
            <Row nm="S3 · повышение квалификации" val={num(me.s3)} pill={{ t: 'ДОКУМЕНТ', cls: 'reg' }} />
            <Row nm="S4 · иная деятельность" val={num(me.s4)} pill={{ t: 'ДОКУМЕНТ', cls: 'reg' }} />
          </Rows>
        </Panel>
      </>

      <Panel
        title={'История судейства · ' + tours.length + ' записи за сезон'}
        extra={<Cap>кем был на старте и почему такой коэффициент</Cap>}
        flush
      >
        <TourTable tours={tours} cols={['Соревнование', 'Роль в наряде', 'Балл']} committee />
        <Foot>
          Коэффициент 1,5 — за роль в бригаде (главный судья, заместитель, секретарь) и за выезд на
          республиканские из другого региона (TZ §7.2). ⚠ Что считать «отсудил соревнование» —
          вопрос 17.4
        </Foot>
      </Panel>
    </>
  );
}
