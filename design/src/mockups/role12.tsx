/** Срок заявки — отдельным однодневным событием. Дату берём из той же колонки
    «Срок или итог» («заявка до 28.04», «исправить до 31.03», «заявка с 10.08»),
    а не заводим вторым полем: два места для одного числа разъедутся, и в
    списке будет одно, а в календаре другое. «Подана 22.05» сроком не считается
    — от региона там уже ничего не ждут. */
const DUE = /(?:^|[\s·])(до|с) (\d{2})\.(\d{2})/;

const dueEvent = (s: Start): CalEvent | undefined => {
  const hit = DUE.exec(s.val);
  if (!hit) return undefined;
  const [, word, day, month] = hit;
  const hot = word === 'до';
  return {
    id: `срок-${s.nm}`,
    nm: hot ? `Заявка до ${day}.${month}` : `Приём заявок с ${day}.${month}`,
    from: `2026-${month}-${day}`,
    /* Горящий срок — жёлтым, дата открытия приёма — серым: первое требует
       действия сейчас, второе только помечает, когда оно начнётся. */
    tone: hot ? 'warning' : 'neutral',
    sub: s.nm,
    to: startTo(s.st),
  };
};

const CAL_EVENTS: CalEvent[] = STARTS.flatMap((s) => {
  const due = dueEvent(s);
  return due ? [startEvent(s), due] : [startEvent(s)];
});

/** «Ближайшее» рядом с сеткой: месяц кончается, а сезон нет — список добирает
    то, что за краем апреля (майский старт, июньская заявка). Собран из тех же
    событий, руками ничего не переписано. */
const SOON12_2 = CAL_EVENTS
  /* Идущее сейчас остаётся в списке: сравниваем по последнему дню, а не по
     первому — иначе старт, который идёт с 14-го, пропал бы 15-го. Строки
     ГГГГ-ММ-ДД сравниваются как даты. */
  .filter((e) => (e.till ?? e.from) >= CAL_TODAY)
  .sort((a, b) => a.from.localeCompare(b.from))
