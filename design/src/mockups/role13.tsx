/** Срок — это день, а не отрезок, и отдельного поля с датой в данных нет: он
    живёт строкой «состав до 08.05» в колонке «срок или итог». Число берём из
    той же строки — второго источника сроков в файле заводить нельзя, они
    разъедутся. */
const dueDay = (text: string) => {
  const hit = /до (\d{2})\.(\d{2})/.exec(text);
  return hit ? `2026-${hit[2]}-${hit[1]}` : undefined;
};

