/* Сквозной ход турнира — от заведения в календаре до пересчёта рейтинга.

   Поэкранные флоу (`flows/*.md`) описывают каждую роль отдельно: маршрут
   администратора, маршрут судьи, маршрут спортсмена. Но турнир идёт **через
   все роли сразу**, и по четырнадцати отдельным маршрутам не видно главного:
   не выпал ли шаг между ролями. Федерация опубликовала — а кто открыл приём
   заявок судей? Судья закрыл приём — а кто строит сетку, судья или секретарь?
   Протокол утверждён — а где видно, что рейтинг пересчитан?

   Здесь тот же материал собран поперёк: состояние турнира (TZ §4.3) → шаги
   внутри него → кто делает шаг и на каком экране.

   **Путей три — по числу категорий календаря** (§4.1, §8.2), и различаются они
   прежде всего тем, кто заявляет: главные старты — старший тренер региона,
   Евразийскую лигу — администратор клуба командой, открытый турнир — спортсмен
   сам. Всё, что общего (судьи, сетка, ход, протокол, рейтинг), написано один
   раз в `stages()` и подставляется каждому пути: разъехаться этим трём
   описаниям нечем, а различия лежат в самих категориях ниже.

   Клубные турниры сюда не входят — они вне контура флоу (решение 11.08.2026,
   `flows/README.md`).

   Ничего нового про систему эти данные не заводят: каждый шаг ссылается на
   существующий экран, а места, где экрана нет, помечены — они и есть ответ на
   вопрос «не пропустили ли мы чего-нибудь важного».

   Источники: TZ §4.1 (категории), §4.3 (состояния), §4.4–4.6 (создание,
   система проведения, протокол), §7 (рейтинг), §8.2 (кто заявляет),
   QUESTIONS §11 (Евразийская лига), поэкранные флоу `flows/*.md`. */

import type { Mark } from '../types';

/** Шаг хода турнира: что происходит, кто делает и на каком экране. */
export type Step = {
  /** Что происходит — действием, а не названием экрана. */
  t: string;
  /** Кто делает: номер роли и короткое имя. */
  who: string;
  /** Экран, на котором это происходит. Без кода — шага в макетах нет. */
  code?: string;
  /** Чем шаг кончается: что меняется в турнире или что видит следующий. */
  out?: string;
  mark?: Mark;
  /** Ветка, а не главный путь: отказ, возврат, отмена, параллельный зритель. */
  side?: boolean;
  /** Чего на этом шаге не хватает: пояснение к ⚠. */
  gap?: string;
};

/** Состояние турнира (TZ §4.3) и всё, что происходит внутри него. */
export type Stage = {
  /** Состояние турнира — дословно из §4.3. */
  st: string;
  /** Кто действует в этом состоянии — по таблице §4.3. */
  who: string;
  /** Что происходит — одной строкой. */
  what: string;
  steps: Step[];
};

/** Путь одной категории календаря. */
export type Tour = {
  key: string;
  /** Категория — как она называется в календаре федерации. */
  title: string;
  /** Что входит в категорию: восемь стартов, шесть лиг, именные опены. */
  sub: string;
  /** Вводная над картой: чем этот путь отличается от соседних. */
  lead: string;
  stages: Stage[];
  /** Чего не хватает именно здесь — видно только поперёк ролей. */
  gaps: string[];
};

