/* Схема поэкранных флоу (источник — корневой `flows/*.md`).

   Один `Screen` = один узел флоу = одна история Storybook. Поля повторяют
   структуру разделов в markdown: как попадает → что на экране → действия →
   состояния. Данные держим отдельно от вёрстки: `data/roleNN.ts` — только
   содержание, `spec.tsx` — только показ. */

/** ✳ — наше решение (подтвердить у федерации) · ⚠ — открытый вопрос. */
export type Mark = 'ours' | 'open';

/** Зона экрана: шапка, список, карточка, форма — из чего собирается макет. */
export type Zone = {
  title: string;
  /** Состав зоны: поля, колонки списка, бейджи, счётчики. */
  items: string[];
  note?: string;
  mark?: Mark;
};

/** Строка таблицы действий: что нажимает, когда доступно, что происходит. */
export type Action = {
  el: string;
  /** Условие доступности — обычно состояние турнира (TZ §4.3). */
  when?: string;
  effect: string;
  mark?: Mark;
  /** Куда ведёт: код экрана этой же роли (`Э6.3`). */
  to?: string;
};

/** Состояние экрана: пусто, ожидание чужого решения, недоступное действие. */
export type State = {
  title: string;
  text?: string;
  tone?: 'info' | 'success' | 'warning' | 'danger';
};

export type Screen = {
  /** Код экрана, общий с `flows/*.md` и схемой `flow-roles.d2`: `Э6.2`. */
  id: string;
  title: string;
  /** Вводная строка: чем экран является, если это не очевидно из названия. */
  note?: string;
  /** Как попадает: пункт меню, переход, уведомление. */
  entry: string[];
  zones: Zone[];
  actions: Action[];
  states: State[];
  mark?: Mark;
};

export type RoleFlow = {
  /** Номер роли по документу федерации (TZ §2). У пары ролей — `3 и 4`. */
  num: string;
  title: string;
  /** Функционал ролью по документу федерации — дословно. */
  duty: string;
  device: string;
  /** Область роли: система, турнир, клуб, регион, стол. */
  scope?: string;
  /** Маршрут словами: с чего начинает и куда идёт. */
  route: string;
  /** Роль целиком не описана в документе — весь флоу гипотеза (роли 8 и 11). */
  hypothesis?: string;
  screens: Screen[];
  /** Чего роль не может — граница с соседними ролями. */
  cannot: string[];
  /** Открытые вопросы к федерации по этой роли. */
  questions: string[];
  /** Файл-источник в корне репозитория. */
  source: string;
};

/* Номер в заголовке дополняем нулём (`01`, `02`, …): Storybook сортирует
   разделы строкой, и без этого порядок был бы 1, 10, 11, …, 2, 3. Пара ролей
   («3 и 4») превращается в `03–04` — сортируется по первому номеру. */
const pad = (num: string) => (num.match(/\d+/g) ?? ['0']).map((n) => n.padStart(2, '0')).join('–');

/** Заголовок раздела роли в дереве Storybook. */
export const roleTitle = (r: RoleFlow) => `Флоу/${pad(r.num)} · ${r.title}`;

/** Имя истории экрана — оно же подпись в боковом меню. */
export const screenName = (s: Screen) => `${s.id} · ${s.title}`;
