/* Округление до двух знаков — §6.4 и §17.5 Положения.

   Math.round половину гонит к плюс-бесконечности: у −0,125 он даёт −0,12, а у
   0,125 — 0,13. Для рейтинга, где падение и рост обязаны считаться одинаково
   (§12.3), это перекос, поэтому половина уходит от нуля в обе стороны. */

export const round2 = (x: number): number => {
  const s = x < 0 ? -1 : 1;
  return (s * Math.round(Math.abs(x) * 100 + Number.EPSILON)) / 100;
};
