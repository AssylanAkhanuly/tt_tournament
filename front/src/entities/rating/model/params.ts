/* Параметры расчёта и — главное — происхождение каждого числа.

   Половина коэффициентов в Положении названа, но не задана: D (§9.4), K
   стандартный и переходный (§11), потолок изменения за матч (§12.1), Rmax и K
   перевода из ITTF (§17.4 — «для целей примера»). Считать без них нельзя,
   поэтому у калькулятора есть значения по умолчанию — но они наши, не
   федерации, и обязаны быть видимы как наши. Отсюда таблица PARAM_SOURCES:
   на экране рядом с каждым полем стоит, откуда взято число. */

import type { Level } from './types';

/** Как применяется коэффициент призового места. В Положении два разных
    прочтения: §9.2 ставит P внутрь формулы каждого матча, §10.6 — «применяется
    после определения рейтингового изменения по результатам матчей турнира». */
export type PrizeMode = 'заматч' | 'затурнир' | 'нет';

/** От какого значения считаются матчи одного турнира. Положение не говорит:
    §8.1–8.2 («расчёт по итоговому протоколу») читается как «от рейтинга до
    турнира», таблица §20 — как «поматчево». */
export type Baseline = 'поматчево' | 'дотурнира';

export type RatingParams = {
  /** D — масштаб шкалы (§9.4). Значение в Положении не указано. */
  D: number;
  /** K с 21-го матча (§11.4). Значение не указано. */
  kStandard: number;
  /** K переходного периода (§11.2). Значение не указано. */
  kTransition: number;
  /** Длина переходного периода в матчах — §11.2–11.3, задано: 20. */
  transitionMatches: number;
  /** Потолок изменения за матч (§12.1). Значение не указано; 0 — без потолка. */
  maxDelta: number;
  /** Резать ли потолком переходный период. В Положении не разделено. */
  capInTransition: boolean;
  /** Коэффициент уровня соревнования — таблица §13, задана. */
  levelC: Record<Level, number>;
  prizeMode: PrizeMode;
  baseline: Baseline;
  /** Нижняя граница рейтинга — §15.15, задано: 0,00. */
  minRating: number;
  /** Перевод позиции ITTF: R = rMax − k × ln(N) (§17.4). */
  ittf: { rMax: number; k: number };
};

