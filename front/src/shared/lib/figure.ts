/* Заглушка фигуры спортсмена ✳ (22.11.2026; общая с 23.11.2026): у кого нет
   своего снимка, тому — фигура своего пола. Ею пользуются состав сборной,
   табло судьи стола, карточки рейтинг-листа, шапка профиля и аватары в таблицах.

   С 27.11.2026 (решение владельца продукта: «у кого нет снимка — контур
   игрока, мужской и женский») заглушка — **контур**, а не сгенерированная
   фотография: живой снимок незнакомого человека читался как фото самого
   спортсмена. Контуров два — `outline-m`, `outline-f` в `public/national/players/`;
   их обвели по прежним заглушкам fal.ai (силуэт по маске и главные линии —
   ворот, ракетка, руки), цвет — серый бренда. Пол неизвестен — один из двух,
   один и тот же для человека (по id). */

const OUTLINE = { m: 'outline-m', f: 'outline-f' } as const;

export function placeholderFigure(id: string, sex?: string | null): string {
  let h = 0;
  for (const ch of id) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  const kind = sex === 'm' || sex === 'f' ? sex : h % 2 ? 'f' : 'm';
  return `/national/players/${OUTLINE[kind]}.webp`;
}
